pub fn offer_pagination_keyboard(part: usize) -> InlineKeyboardMarkup {
    let mut row = Vec::new();
    if part > 1 {
        row.push(InlineKeyboardButton::callback("⬅️ Назад", format!("legal:offer:{}", part - 1)));
    }
    if part < 3 {
        row.push(InlineKeyboardButton::callback("Далее ➡️", format!("legal:offer:{}", part + 1)));
    }
    
    InlineKeyboardMarkup::new(vec![
        row,
        vec![InlineKeyboardButton::callback("⚖️ Назад к списку документов", "nav:legal")],
        vec![InlineKeyboardButton::callback("← Главное меню", "nav:main_menu")],
    ])
}
