/// Формирование контекста запроса для расклада Таро
pub fn build_tarot_prompt(
    sphere_title: &str,
    subtopic_title: &str,
    spread_name: &str,
    cards: &[(&str, bool)], // (название карты, перевернутая ли)
) -> String {
    let mut cards_desc = String::new();
    for (idx, (name, is_reversed)) in cards.iter().enumerate() {
        let position = if *is_reversed { "в перевернутом положении" } else { "в прямом положении" };
        cards_desc.push_str(&format!("{}. Карта: <b>{}</b> ({})\n", idx + 1, name, position));
    }

    format!(
        r#"Сделай глубокое толкование расклада Таро.

📍 <b>Сфера жизни</b>: {}
❓ <b>Аспект/Вопрос</b>: {}
🃏 <b>Тип расклада</b>: {}

🎴 <b>Выпавшие арканы</b>:
{}

Пожалуйста, раскрой значение каждого аркана в контексте заданного вопроса и дай синтезированный мудрый совет."#,
        sphere_title, subtopic_title, spread_name, cards_desc
    )
}

